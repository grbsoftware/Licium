# gen_palette_lib.ps1 — regenerate vis_milk2\licium_palette_lib.h from its
# public sources. Part of the Palettes v1 clean-room boundary (see
# docs\PALETTES_DESIGN.md): the curated library is REGENERATED from the
# original MIT-licensed repos, never carried from the old closed tree.
#
# Sources:
#   1. Experience-Monks/nice-color-palettes (MIT) — 1000 community palettes
#      of 5 colors; we take the first 500 (the top-rated ones).
#   2. mattdesl/dictionary-of-colour-combinations (MIT) — Sanzo Wada's
#      "A Dictionary of Colour Combinations" reconstructed as colors.json;
#      palettes are recovered by grouping colors on shared `combinations` ids.
#
# Run from anywhere; writes the header next to the other vis_milk2 sources.
# Deterministic: same source data -> byte-identical header (verification #7).

$ErrorActionPreference = "Stop"
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12

$outPath = Join-Path $PSScriptRoot "..\vis_milk2\licium_palette_lib.h"

Write-Host "fetching nice-color-palettes (1000.json)..."
$nice = Invoke-WebRequest -UseBasicParsing `
  "https://raw.githubusercontent.com/Experience-Monks/nice-color-palettes/master/1000.json" |
  Select-Object -ExpandProperty Content | ConvertFrom-Json

Write-Host "fetching dictionary-of-colour-combinations (colors.json)..."
$wadaColors = Invoke-WebRequest -UseBasicParsing `
  "https://raw.githubusercontent.com/mattdesl/dictionary-of-colour-combinations/master/colors.json" |
  Select-Object -ExpandProperty Content | ConvertFrom-Json

# --- assemble palettes as lists of 0xRRGGBB uints -----------------------------
$palettes = New-Object System.Collections.ArrayList

function HexToUint([string]$hex) {
  [Convert]::ToUInt32($hex.TrimStart('#'), 16)
}

# 1) first 500 community palettes (each is exactly 5 hex strings)
foreach ($pal in ($nice | Select-Object -First 500)) {
  $cols = @($pal | ForEach-Object { HexToUint $_ })
  [void]$palettes.Add($cols)
}
$niceCount = $palettes.Count

# 2) Sanzo Wada: group colors by combination id (a color lists every combo it
# belongs to). Combos have 2-4 colors; keep 2..5.
$combos = @{}
foreach ($c in $wadaColors) {
  if (-not $c.combinations) { continue }
  foreach ($id in $c.combinations) {
    if (-not $combos.ContainsKey($id)) { $combos[$id] = New-Object System.Collections.ArrayList }
    [void]$combos[$id].Add((HexToUint $c.hex))
  }
}
$wadaCount = 0
foreach ($id in ($combos.Keys | Sort-Object {[int]$_})) {
  $cols = $combos[$id]
  if ($cols.Count -ge 2 -and $cols.Count -le 5) {
    [void]$palettes.Add(@($cols))
    $wadaCount++
  }
}

Write-Host "palettes: $niceCount community + $wadaCount Sanzo Wada = $($palettes.Count) total"

# --- emit the header (CRLF, ASCII) --------------------------------------------
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// licium_palette_lib.h -- AUTO-GENERATED by tools\gen_palette_lib.ps1. Do not hand-edit.")
[void]$sb.AppendLine("//")
[void]$sb.AppendLine("// Curated palette library for the Palettes pillar (docs\PALETTES_DESIGN.md).")
[void]$sb.AppendLine("// Regenerated from public MIT-licensed sources -- never carried from the old tree:")
[void]$sb.AppendLine("//   - Experience-Monks/nice-color-palettes (first 500 of 1000.json)")
[void]$sb.AppendLine("//   - mattdesl/dictionary-of-colour-combinations (Sanzo Wada, grouped on combination ids)")
[void]$sb.AppendLine("//")
[void]$sb.AppendLine("// $niceCount community + $wadaCount Sanzo Wada = $($palettes.Count) palettes, 2..5 colors each, 0xRRGGBB.")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("#ifndef LICIUM_PALETTE_LIB_H")
[void]$sb.AppendLine("#define LICIUM_PALETTE_LIB_H")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("typedef struct { unsigned char n; unsigned int c[5]; } LiciumLibPalette;")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("static const LiciumLibPalette LICIUM_PAL_LIB[] = {")
foreach ($cols in $palettes) {
  $hexes = @($cols | ForEach-Object { "0x{0:X6}" -f $_ })
  while ($hexes.Count -lt 5) { $hexes += "0x000000" }
  [void]$sb.AppendLine("    { $($cols.Count), { $($hexes -join ', ') } },")
}
[void]$sb.AppendLine("};")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("#define LICIUM_PAL_LIB_COUNT (sizeof(LICIUM_PAL_LIB)/sizeof(LICIUM_PAL_LIB[0]))")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("#endif // LICIUM_PALETTE_LIB_H")

[IO.File]::WriteAllText($outPath, $sb.ToString(), [Text.Encoding]::ASCII)
Write-Host "wrote $outPath"
